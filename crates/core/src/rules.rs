//! Правила почты (S4-07): простая модель «условие → действие» и её скрипт Sieve (RFC 5228). Чистый модуль: без
//! сети, разбор и генерация — с тестами. Правила выполняет сервер при доставке письма.
//!
//! Скрипт пишет только [`generate`]: строка на правило, выключенное — комментарием `# off: …`. Разбор
//! ([`parse`]) принимает лишь то, что [`generate`] выдал бы из разобранного, байт в байт; любой другой скрипт —
//! «чужой» (показывается текстом, без замены по умолчанию).

/// Имя нашего скрипта на сервере.
pub const SCRIPT_NAME: &str = "postman";
/// Скрипт автоответа Stalwart (`VacationResponse`, `docs/STALWART.md`).
pub const VACATION_SCRIPT: &str = "vacation";

const HEADER: &str = "# Postman rules v1: generated by Postman, edit them there";
const OFF: &str = "# off: ";

/// Что проверяет условие: заголовок письма содержит строку.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Field {
    From,
    /// «Кому» и «Копия».
    To,
    Subject,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Action {
    /// В папку: по id (переименование папки не ломает правило), имя — запасное и для показа.
    Move { mailbox_id: String, name: String },
    /// Пометить прочитанным (`\Seen`).
    MarkRead,
    /// Поставить флаг (`\Flagged`).
    Flag,
    /// Удалить без корзины (`discard`).
    Discard,
    /// Переслать копию на адрес (`redirect :copy`), письмо остаётся.
    Redirect(String),
    /// Поставить категорию (S5-26): ключевое слово категории (`pm.cat.<id>` или взятая в таблицу метка Thunderbird)
    /// — `addflag "<слово>"` (`imap4flags`), сервер ставит его письму в `keywords`.
    Category(String),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rule {
    pub enabled: bool,
    pub field: Field,
    pub value: String,
    pub action: Action,
}

/// Скрипт целиком: правила и включение автоответа (Stalwart держит активным один скрипт: при правилах автоответ
/// подключается к ним `include`).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Script {
    pub rules: Vec<Rule>,
    pub vacation: bool,
}

impl Script {
    /// Есть включённые правила — скрипт должен быть активным.
    pub fn has_enabled(&self) -> bool {
        self.rules.iter().any(|r| r.enabled)
    }
}

/// Строка Sieve в кавычках: `\` и `"` экранируются.
pub(crate) fn quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        if matches!(c, '"' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    out
}

fn test(r: &Rule) -> String {
    let header = match r.field {
        Field::From => "\"from\"",
        Field::To => "[\"to\", \"cc\"]",
        Field::Subject => "\"subject\"",
    };
    format!("header :contains {header} {}", quote(&r.value))
}

fn action(a: &Action) -> String {
    match a {
        Action::Move { mailbox_id, name } => format!("fileinto :mailboxid {} {};", quote(mailbox_id), quote(name)),
        Action::MarkRead => "addflag \"\\\\Seen\";".into(),
        Action::Flag => "addflag \"\\\\Flagged\";".into(),
        Action::Discard => "discard;".into(),
        Action::Redirect(to) => format!("redirect :copy {};", quote(to)),
        Action::Category(keyword) => format!("addflag {};", quote(keyword)),
    }
}

fn rule_line(r: &Rule) -> String {
    let line = format!("if {} {{ {} }}", test(r), action(&r.action));
    if r.enabled { line } else { format!("{OFF}{line}") }
}

/// Расширения Sieve, нужные правилам (по всем, и выключенным: включение не меняет `require`).
fn extensions(s: &Script) -> Vec<&'static str> {
    let mut ext = Vec::new();
    for r in &s.rules {
        match r.action {
            // Stalwart требует и `mailbox` для `:mailboxid` (`docs/STALWART.md`).
            Action::Move { .. } => ext.extend(["fileinto", "mailbox", "mailboxid"]),
            Action::MarkRead | Action::Flag | Action::Category(_) => ext.push("imap4flags"),
            Action::Discard => {}
            Action::Redirect(_) => ext.push("copy"),
        }
    }
    if s.vacation {
        ext.push("include");
    }
    ext.sort_unstable();
    ext.dedup();
    ext
}

/// Текст скрипта. Строки — через `\n`, в конце перевод строки.
pub fn generate(s: &Script) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    let ext = extensions(s);
    if !ext.is_empty() {
        let list: Vec<String> = ext.iter().map(|e| quote(e)).collect();
        out.push_str(&format!("require [{}];\n", list.join(", ")));
    }
    if s.vacation {
        out.push_str(&format!("include :personal :optional {};\n", quote(VACATION_SCRIPT)));
    }
    for r in &s.rules {
        out.push_str(&rule_line(r));
        out.push('\n');
    }
    out
}

/// Разбор нашего скрипта; `None` — скрипт не наш или изменён вне Postman.
pub fn parse(text: &str) -> Option<Script> {
    let text = text.replace("\r\n", "\n");
    let mut lines = text.lines();
    if lines.next()? != HEADER {
        return None;
    }
    let mut script = Script::default();
    for line in lines {
        if line.starts_with("require ") {
            continue;
        }
        if line.starts_with("include ") {
            script.vacation = true;
            continue;
        }
        let (enabled, body) = match line.strip_prefix(OFF) {
            Some(rest) => (false, rest),
            None => (true, line),
        };
        script.rules.push(parse_rule(enabled, body)?);
    }
    // Только то, что сгенерировали бы сами: иначе скрипт правили руками.
    (generate(&script) == text).then_some(script)
}

fn parse_rule(enabled: bool, line: &str) -> Option<Rule> {
    let rest = line.strip_prefix("if header :contains ")?;
    let (field, rest) = if let Some(r) = rest.strip_prefix("\"from\" ") {
        (Field::From, r)
    } else if let Some(r) = rest.strip_prefix("[\"to\", \"cc\"] ") {
        (Field::To, r)
    } else {
        (Field::Subject, rest.strip_prefix("\"subject\" ")?)
    };
    let (value, rest) = unquote(rest)?;
    let body = rest.strip_prefix(" { ")?.strip_suffix(" }")?;
    let action = if let Some(r) = body.strip_prefix("fileinto :mailboxid ") {
        let (mailbox_id, r) = unquote(r)?;
        let (name, r) = unquote(r.strip_prefix(' ')?)?;
        (r == ";").then_some(Action::Move { mailbox_id, name })?
    } else if let Some(r) = body.strip_prefix("redirect :copy ") {
        let (to, r) = unquote(r)?;
        (r == ";").then_some(Action::Redirect(to))?
    } else if let Some(r) = body.strip_prefix("addflag ") {
        let (flag, r) = unquote(r)?;
        if r != ";" {
            return None;
        }
        match flag.as_str() {
            "\\Seen" => Action::MarkRead,
            "\\Flagged" => Action::Flag,
            // Системные флаги (`\Answered`…) — не наши; категория — ключевое слово без `\`.
            k if !k.is_empty() && !k.starts_with('\\') => Action::Category(flag),
            _ => return None,
        }
    } else if body == "discard;" {
        Action::Discard
    } else {
        return None;
    };
    Some(Rule { enabled, field, value, action })
}

/// Строка в кавычках в начале `s` → (значение, остаток после закрывающей кавычки).
fn unquote(s: &str) -> Option<(String, &str)> {
    let mut chars = s.strip_prefix('"')?.char_indices();
    let mut out = String::new();
    while let Some((i, c)) = chars.next() {
        match c {
            '\\' => out.push(chars.next()?.1),
            '"' => return Some((out, &s[i + 2..])),
            c => out.push(c),
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Script {
        Script {
            rules: vec![
                Rule {
                    enabled: true,
                    field: Field::Subject,
                    value: "Отчёт \"Q3\" \\ итог".into(),
                    action: Action::Move { mailbox_id: "a1".into(), name: "Отчёты".into() },
                },
                Rule { enabled: false, field: Field::From, value: "spam@x.ru".into(), action: Action::Discard },
                Rule { enabled: true, field: Field::To, value: "team@corp".into(), action: Action::MarkRead },
                Rule { enabled: true, field: Field::From, value: "boss".into(), action: Action::Flag },
                Rule { enabled: true, field: Field::Subject, value: "срочно".into(), action: Action::Redirect("me@home.example".into()) },
                Rule { enabled: true, field: Field::Subject, value: "тендер".into(), action: Action::Category("pm.cat.tenders".into()) },
                Rule { enabled: false, field: Field::From, value: "tb".into(), action: Action::Category("$label2".into()) },
            ],
            vacation: true,
        }
    }

    #[test]
    fn generated_script() {
        let text = generate(&sample());
        let want = [
            HEADER,
            r#"require ["copy", "fileinto", "imap4flags", "include", "mailbox", "mailboxid"];"#,
            r#"include :personal :optional "vacation";"#,
            r#"if header :contains "subject" "Отчёт \"Q3\" \\ итог" { fileinto :mailboxid "a1" "Отчёты"; }"#,
            r#"# off: if header :contains "from" "spam@x.ru" { discard; }"#,
            r#"if header :contains ["to", "cc"] "team@corp" { addflag "\\Seen"; }"#,
            r#"if header :contains "from" "boss" { addflag "\\Flagged"; }"#,
            r#"if header :contains "subject" "срочно" { redirect :copy "me@home.example"; }"#,
            r#"if header :contains "subject" "тендер" { addflag "pm.cat.tenders"; }"#,
            r#"# off: if header :contains "from" "tb" { addflag "$label2"; }"#,
        ]
        .map(|l| format!("{l}\n"))
        .concat();
        assert_eq!(text, want);
        // Без правил и автоответа — только заголовок.
        assert_eq!(generate(&Script::default()), format!("{HEADER}\n"));
    }

    #[test]
    fn our_script_round_trips() {
        for s in [sample(), Script::default(), Script { vacation: true, ..Default::default() }] {
            assert_eq!(parse(&generate(&s)), Some(s.clone()));
            // Сервер мог отдать с CRLF.
            assert_eq!(parse(&generate(&s).replace('\n', "\r\n")), Some(s));
        }
        assert!(sample().has_enabled());
        assert!(!Script::default().has_enabled());
    }

    #[test]
    fn foreign_or_edited_scripts_are_not_ours() {
        let text = generate(&sample());
        // Чужой скрипт, наш без заголовка, лишняя строка, другое расширение, правка правила руками.
        assert_eq!(parse("require \"fileinto\";\nif true { fileinto \"X\"; }\n"), None);
        assert_eq!(parse(text.split_once('\n').unwrap().1), None);
        assert_eq!(parse(&format!("{text}keep;\n")), None);
        assert_eq!(parse(&text.replace("\"copy\", ", "")), None);
        assert_eq!(parse(&text.replace(":contains \"from\" \"boss\"", ":is \"from\" \"boss\"")), None);
        assert_eq!(parse(&text.replace("{ discard; }", "{ discard; stop; }")), None);
        assert_eq!(parse(&text.replace("\"a1\" \"Отчёты\"", "\"a1\"")), None);
        // Системный флаг вместо категории и лишнее после `addflag` — не наше.
        assert_eq!(parse(&text.replace("\"pm.cat.tenders\"", "\"\\\\Answered\"")), None);
        assert_eq!(parse(&text.replace("addflag \"pm.cat.tenders\";", "addflag \"pm.cat.tenders\" \"x\";")), None);
        assert_eq!(parse(""), None);
    }

    #[test]
    fn quoting() {
        assert_eq!(quote(r#"a"b\c"#), r#""a\"b\\c""#);
        assert_eq!(unquote(r#""a\"b\\c" rest"#), Some((r#"a"b\c"#.to_string(), " rest")));
        assert_eq!(unquote(r#""unterminated"#), None);
        assert_eq!(unquote("no quote"), None);
    }
}
