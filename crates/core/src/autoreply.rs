//! Автоответ Postman (S5-29, `docs/DESIGN.md` «Автоответ и квота»): тексты «Внутри компании» и «Внешним», «только
//! контактам», «не отвечать повторно N дней», Markdown, «Вне офиса» в календаре. Чистый модуль: модель, её скрипт
//! Sieve `vacation` (RFC 5230) и событие «Вне офиса»; сеть — `settings.rs`.
//!
//! У `VacationResponse` JMAP один текст и нет условий, поэтому Postman пишет скрипт автоответа сам: сначала
//! `VacationResponse/set` (включение и период — для других клиентов и самого сервера), затем поверх скрипта
//! `vacation` — свой ([`script`]). Правила (S4-07) подключают его тем же `include`. Настройки — строкой JSON в
//! комментарии скрипта ([`parse`]); адреса контактов и свои домены в них не хранятся, они подставляются при записи.
//! Другой клиент перепишет скрипт через `VacationResponse/set` — заголовка не станет, и Postman покажет то, что
//! вернул сервер. Как Stalwart принимает свой скрипт `vacation`, записанный клиентом, — [проверить на стенде]:
//! `stand_settings::autoreply_split_texts`.

use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

use crate::rules::quote;

/// Первая строка своего скрипта.
pub const HEADER: &str = "# Postman autoreply v1: generated by Postman, edit it there";
const SETTINGS: &str = "# settings: ";
/// «Не отвечать повторно одному адресату» — дней по умолчанию (макет «Настройки → Автоответ»).
pub const DAYS: u16 = 4;
/// Меньше суток Sieve `vacation` не умеет (RFC 5230 §4.1, `:days` ≥ 1): «на каждое письмо» — раз в сутки.
const MIN_DAYS: u16 = 1;
const MAX_DAYS: u16 = 365;
/// Адресов контактов в скрипте — не больше (размер скрипта; остальные внешние — без ответа).
pub const MAX_CONTACTS: usize = 2000;
const BOUNDARY: &str = "postman-autoreply";

/// Тема и текст (Markdown) ответа одной группе.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct Text {
    pub subject: String,
    pub body: String,
}

impl Text {
    /// Пустой текст — этой группе без ответа.
    pub fn is_empty(&self) -> bool {
        self.body.trim().is_empty()
    }
}

/// Настройки автоответа сверх `VacationResponse`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct AutoReply {
    /// Коллегам: отправитель из своих доменов.
    pub internal: Text,
    pub external: Text,
    /// Внешним — только адресатам из моих контактов.
    pub contacts_only: bool,
    /// Одному адресату — не чаще раза в [`AutoReply::days`] дней; выключено — раз в сутки (меньше Sieve не умеет).
    pub once: bool,
    pub days: u16,
    /// На период — событие «Вне офиса» в календаре.
    pub out_of_office: bool,
}

impl Default for AutoReply {
    fn default() -> Self {
        Self { internal: Text::default(), external: Text::default(), contacts_only: true, once: true, days: DAYS, out_of_office: true }
    }
}

impl AutoReply {
    /// `:days` скрипта.
    pub fn days(&self) -> u16 {
        if self.once { self.days.clamp(MIN_DAYS, MAX_DAYS) } else { MIN_DAYS }
    }

    /// Автоответ сервера без своего скрипта (другой клиент или Postman до S5-29): один текст всем.
    pub fn from_server(subject: Option<&str>, body: Option<&str>) -> AutoReply {
        let t = Text { subject: subject.unwrap_or_default().to_owned(), body: body.unwrap_or_default().to_owned() };
        AutoReply { internal: t.clone(), external: t, contacts_only: false, ..AutoReply::default() }
    }

    /// Текст для `VacationResponse` (другие клиенты видят один): внешний, без него — коллегам.
    pub fn primary(&self) -> &Text {
        if self.external.is_empty() { &self.internal } else { &self.external }
    }

    /// Кому уходит ответ — для полосы «Автоответ включён» и предпросмотра.
    pub fn audience(&self) -> Reach {
        match (!self.internal.is_empty(), !self.external.is_empty(), self.contacts_only) {
            (true, true, true) => Reach::ColleaguesAndContacts,
            (true, true, false) => Reach::Everyone,
            (true, false, _) => Reach::Colleagues,
            (false, true, true) => Reach::Contacts,
            (false, true, false) => Reach::External,
            (false, false, _) => Reach::Nobody,
        }
    }
}

/// Кому уходит ответ.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reach {
    ColleaguesAndContacts,
    Everyone,
    Colleagues,
    Contacts,
    External,
    Nobody,
}

impl Reach {
    /// Для ключей текстов (`vacation-reach-<id>`).
    pub fn id(self) -> &'static str {
        match self {
            Reach::ColleaguesAndContacts => "colleagues-contacts",
            Reach::Everyone => "everyone",
            Reach::Colleagues => "colleagues",
            Reach::Contacts => "contacts",
            Reach::External => "external",
            Reach::Nobody => "nobody",
        }
    }
}

/// То, что лежит в заголовке скрипта: настройки, период (UTCDate JMAP) и uid события «Вне офиса».
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct Stored {
    pub reply: AutoReply,
    pub from: Option<String>,
    pub to: Option<String>,
    /// Событие «Вне офиса», которое поставил Postman: при следующей записи — заменить или убрать.
    pub ooo: Option<String>,
}

/// Кому отвечать: свои домены (внутри компании), адреса моих контактов (внешним при «только контактам») и мои
/// адреса (`:addresses` — письма на псевдонимы тоже получают ответ).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Audience {
    pub domains: Vec<String>,
    pub contacts: Vec<String>,
    pub mine: Vec<String>,
}

fn sorted(mut v: Vec<String>) -> Vec<String> {
    v.sort_unstable();
    v.dedup();
    v
}

impl Audience {
    /// Домены и адреса в нижнем регистре без повторов; контакты — только внешние (свои домены и так «внутри»), не
    /// больше [`MAX_CONTACTS`].
    pub fn normalized(&self) -> Audience {
        let domains = sorted(self.domains.iter().map(|d| d.trim().trim_start_matches('@').to_lowercase()).filter(|d| !d.is_empty()).collect());
        let own = |a: &str| a.rsplit_once('@').is_some_and(|(_, d)| domains.iter().any(|x| x == d));
        let address = |a: &String| Some(a.trim().to_lowercase()).filter(|a| a.contains('@') && !a.contains(char::is_whitespace));
        let mut contacts = sorted(self.contacts.iter().filter_map(address).filter(|a| !own(a)).collect());
        contacts.truncate(MAX_CONTACTS);
        let mine = sorted(self.mine.iter().filter_map(address).collect());
        Audience { domains, contacts, mine }
    }

    /// Домены адресов.
    pub fn domains_of(addresses: &[String]) -> Vec<String> {
        sorted(addresses.iter().filter_map(|a| a.rsplit_once('@')).map(|(_, d)| d.trim().to_lowercase()).collect())
    }
}

/// Список строк Sieve: `["a", "b"]`.
fn list(items: &[String]) -> String {
    let q: Vec<String> = items.iter().map(|s| quote(s)).collect();
    format!("[{}]", q.join(", "))
}

/// Тело ответа MIME: текст (Markdown как есть) и HTML из него (`postman_ir::markdown_to_html`, как у письма).
pub fn mime(body: &str) -> String {
    let crlf = |s: &str| s.replace("\r\n", "\n").replace('\n', "\r\n");
    let text = crlf(body.trim_end());
    let html = crlf(&postman_ir::markdown_to_html(body.trim_end()));
    format!(
        "Content-Type: multipart/alternative; boundary=\"{BOUNDARY}\"\r\n\r\n\
         --{BOUNDARY}\r\nContent-Type: text/plain; charset=utf-8\r\nContent-Transfer-Encoding: 8bit\r\n\r\n{text}\r\n\
         --{BOUNDARY}\r\nContent-Type: text/html; charset=utf-8\r\nContent-Transfer-Encoding: 8bit\r\n\r\n{html}\r\n\
         --{BOUNDARY}--\r\n"
    )
}

fn vacation(reply: &AutoReply, t: &Text, mine: &[String], indent: &str) -> String {
    let subject = if t.subject.trim().is_empty() { String::new() } else { format!(" :subject {}", quote(t.subject.trim())) };
    let addresses = if mine.is_empty() { String::new() } else { format!(" :addresses {}", list(mine)) };
    format!("{indent}vacation :days {}{subject}{addresses} :mime {};\n", reply.days(), quote(&mime(&t.body)))
}

/// UTC-дата `2026-10-21T06:00:00Z` без зоны и долей — для сравнения с `currentdate … "iso8601"` (тот добавляет зону:
/// строка короче — меньше при равных секундах).
fn bound(utc: &str) -> String {
    utc.trim().trim_end_matches('Z').chars().take(19).collect()
}

/// Скрипт `vacation`: период, коллегам — свой текст, внешним — свой (при «только контактам» — адресатам из
/// `audience.contacts`). Пустой текст — группе без ответа.
pub fn script(stored: &Stored, audience: &Audience) -> String {
    let reply = &stored.reply;
    let a = audience.normalized();
    let mut out = format!("{HEADER}\n{SETTINGS}{}\n", serde_json::to_string(stored).unwrap_or_default());
    let dates: Vec<String> = [(&stored.from, "ge"), (&stored.to, "lt")]
        .into_iter()
        .filter_map(|(d, op)| d.as_deref().map(|d| format!("currentdate :zone \"+0000\" :value \"{op}\" \"iso8601\" {}", quote(&bound(d)))))
        .collect();
    let mut require = vec!["vacation".to_owned()];
    if !dates.is_empty() {
        require.extend(["date".to_owned(), "relational".to_owned()]);
    }
    out.push_str(&format!("require {};\n", list(&require)));
    let base = if dates.is_empty() { "" } else { "    " };
    let inner = format!("{base}    ");
    // Ветки по порядку: условие (`None` — «остальным») и тело (`None` — без ответа).
    let mut branches: Vec<(Option<String>, Option<String>)> = Vec::new();
    // Коллеги — первыми: их письма во внешнюю ветку не попадают и с пустым текстом.
    if !a.domains.is_empty() {
        let body = (!reply.internal.is_empty()).then(|| vacation(reply, &reply.internal, &a.mine, &inner));
        branches.push((Some(format!("address :domain :is \"from\" {}", list(&a.domains))), body));
    }
    if !reply.external.is_empty() {
        let body = Some(vacation(reply, &reply.external, &a.mine, &inner));
        match (reply.contacts_only, a.contacts.is_empty()) {
            (true, false) => branches.push((Some(format!("address :is \"from\" {}", list(&a.contacts))), body)),
            (true, true) => {}
            (false, _) => branches.push((None, body)),
        }
    }
    // Пустые ветки в конце ничего не меняют.
    while branches.last().is_some_and(|b| b.1.is_none()) {
        branches.pop();
    }
    let mut body = String::new();
    match branches.as_slice() {
        [] => {}
        [(None, Some(text))] => body.push_str(&text.replacen(&inner, base, 1)),
        _ => {
            for (i, (cond, text)) in branches.iter().enumerate() {
                body.push_str(&match (cond, i) {
                    (Some(c), 0) => format!("{base}if {c} {{\n"),
                    (Some(c), _) => format!("{base}}} elsif {c} {{\n"),
                    (None, _) => format!("{base}}} else {{\n"),
                });
                body.push_str(text.as_deref().unwrap_or_default());
            }
            body.push_str(&format!("{base}}}\n"));
        }
    }
    if dates.is_empty() {
        out.push_str(&body);
    } else if !body.is_empty() {
        out.push_str(&format!("if allof ({}) {{\n{body}}}\n", dates.join(", ")));
    }
    out
}

/// Настройки своего скрипта; `None` — скрипт не Postman (записан через `VacationResponse/set` или руками).
pub fn parse(text: &str) -> Option<Stored> {
    let text = text.replace("\r\n", "\n");
    let mut lines = text.lines();
    if lines.next()? != HEADER {
        return None;
    }
    let json = lines.next()?.strip_prefix(SETTINGS)?;
    serde_json::from_str(json).ok()
}

/// Событие «Вне офиса» на весь день за период (`from`/`to` — UTCDate, `to` — исключительно): дни в поясе `tz`,
/// конец в полночь — этот день уже не входит. Занятость — `busy` (JSCalendar `freeBusyStatus` другого не знает;
/// «вне офиса» у сервера — [проверить]). `None` — периода нет.
pub fn out_of_office(title: &str, from: &str, to: &str, tz: &jiff::tz::TimeZone, uid: &str, calendar_id: &str) -> Option<Value> {
    let at = |s: &str| s.parse::<jiff::Timestamp>().ok().map(|t| t.to_zoned(tz.clone()));
    let (start, end) = (at(from)?, at(to)?);
    let first = start.date();
    let last = if end.time() == jiff::civil::Time::midnight() { end.date() } else { end.date().tomorrow().ok()? };
    let days = first.until(last).ok()?.get_days();
    (days > 0).then(|| {
        json!({
            "@type": "Event",
            "uid": uid,
            "calendarIds": { calendar_id: true },
            "title": title,
            "start": format!("{first}T00:00:00"),
            "duration": format!("P{days}D"),
            "showWithoutTime": true,
            "freeBusyStatus": "busy",
            "status": "confirmed",
            "privacy": "public",
        })
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reply() -> AutoReply {
        AutoReply {
            internal: Text {
                subject: "Нет на месте до пт".into(), body: "Коллеги, я в отпуске.\n\n- срочно — **Дмитрий**".into()
            },
            external: Text { subject: "Автоответ".into(), body: "Спасибо за письмо \"вне офиса\".".into() },
            ..AutoReply::default()
        }
    }

    fn stored(reply: AutoReply, from: Option<&str>, to: Option<&str>) -> Stored {
        Stored { reply, from: from.map(Into::into), to: to.map(Into::into), ooo: None }
    }

    fn audience() -> Audience {
        Audience {
            domains: vec!["Corp.Example".into(), "@corp.example".into()],
            contacts: vec!["Partner@Client.example".into(), "me@corp.example".into(), "partner@client.example".into(), "bad".into()],
            mine: vec![],
        }
    }

    /// По умолчанию — по макету: только контактам, раз в 4 дня, «Вне офиса».
    #[test]
    fn defaults_follow_the_mockup() {
        let a = AutoReply::default();
        assert!(a.contacts_only && a.once && a.out_of_office);
        assert_eq!((a.days, a.days()), (4, 4));
        assert_eq!(AutoReply { once: false, ..a.clone() }.days(), 1, "«на каждое письмо» — раз в сутки");
        assert_eq!(AutoReply { days: 0, ..a.clone() }.days(), 1);
        assert_eq!(AutoReply { days: 1000, ..a }.days(), 365);
        let server = AutoReply::from_server(Some("Нет на месте"), Some("В отпуске"));
        assert_eq!((server.internal.body.as_str(), server.external.body.as_str(), server.contacts_only), ("В отпуске", "В отпуске", false));
        assert_eq!(server.audience(), Reach::Everyone);
        assert_eq!(reply().audience(), Reach::ColleaguesAndContacts);
        assert_eq!(AutoReply { external: Text::default(), ..reply() }.audience(), Reach::Colleagues);
        assert_eq!(AutoReply::default().audience(), Reach::Nobody);
        assert_eq!(reply().primary().subject, "Автоответ");
    }

    #[test]
    fn audience_keeps_external_contacts_once() {
        let n = Audience { mine: vec!["Me@Corp.example".into(), "alias@corp.example ".into()], ..audience() }.normalized();
        assert_eq!(n.domains, ["corp.example"]);
        assert_eq!(n.contacts, ["partner@client.example"], "свои — внутри, повтор и не адрес — прочь");
        assert_eq!(n.mine, ["alias@corp.example", "me@corp.example"]);
        assert_eq!(Audience::domains_of(&["a@Corp.example".into(), "b@corp.example".into(), "x".into()]), ["corp.example"]);
    }

    /// Период, коллеги, внешние из контактов: ветки по порядку, строки экранированы, настройки читаются обратно.
    #[test]
    fn split_texts_with_period_and_contacts() {
        let st = stored(reply(), Some("2026-10-21T06:00:00Z"), Some("2026-10-23T15:00:00Z"));
        let s = script(&st, &Audience { mine: vec!["me@corp.example".into()], ..audience() });
        let lines: Vec<&str> = s.lines().collect();
        assert_eq!(lines[0], HEADER);
        assert_eq!(lines[2], r#"require ["vacation", "date", "relational"];"#);
        assert_eq!(
            lines[3],
            r#"if allof (currentdate :zone "+0000" :value "ge" "iso8601" "2026-10-21T06:00:00", currentdate :zone "+0000" :value "lt" "iso8601" "2026-10-23T15:00:00") {"#
        );
        assert_eq!(lines[4], r#"    if address :domain :is "from" ["corp.example"] {"#);
        assert!(lines[5].starts_with(
            r#"        vacation :days 4 :subject "Нет на месте до пт" :addresses ["me@corp.example"] :mime "Content-Type: multipart/alternative"#
        ));
        assert!(s.contains("    } elsif address :is \"from\" [\"partner@client.example\"] {\n"));
        assert!(s.contains(r#"Спасибо за письмо \"вне офиса\"."#), "кавычки в тексте экранированы");
        assert!(s.contains("<strong>Дмитрий</strong>"), "HTML из Markdown");
        assert!(s.ends_with("    }\n}\n"), "{s}");
        assert_eq!(s.matches('{').count(), s.matches('}').count(), "скобки парные");
        assert_eq!(parse(&s), Some(st.clone()));
        assert_eq!(parse(&s.replace('\n', "\r\n")), Some(st));
    }

    /// Без периода и «только контактам»: внешним — веткой `else`; без своих доменов — ответ всем без `if`.
    #[test]
    fn everyone_and_no_period() {
        let r = AutoReply { contacts_only: false, ..reply() };
        let s = script(&stored(r.clone(), None, None), &audience());
        assert!(s.contains("require [\"vacation\"];\nif address :domain :is \"from\" [\"corp.example\"] {\n    vacation :days 4"), "{s}");
        assert!(s.contains("\n} else {\n    vacation :days 4 :subject \"Автоответ\""));
        assert!(s.ends_with("\n}\n"));
        let s = script(&stored(r, None, None), &Audience::default());
        // Тело MIME внутри строки — со своими переводами строк: считаем команды, а не строки.
        assert_eq!(s.matches("vacation :days").count(), 1, "{s}");
        assert!(!s.contains("if "), "{s}");
        assert!(s.lines().nth(3).is_some_and(|l| l.starts_with("vacation :days 4 :subject \"Автоответ\"")));
    }

    /// Пустой текст — группе без ответа: коллеги без текста всё равно не получают внешний ответ.
    #[test]
    fn empty_texts_mean_no_reply() {
        let r = AutoReply { internal: Text::default(), contacts_only: false, ..reply() };
        let s = script(&stored(r, None, None), &audience());
        assert!(s.contains("if address :domain :is \"from\" [\"corp.example\"] {\n} else {\n    vacation"), "{s}");
        // «Только контактам» без контактов и коллегам без текста — ответа нет никому, веток нет.
        let r = AutoReply { internal: Text::default(), ..reply() };
        let st = stored(r, Some("2026-10-21T06:00:00Z"), None);
        let s = script(&st, &Audience { contacts: vec![], ..audience() });
        assert!(!s.contains("vacation :days") && !s.contains("if "), "{s}");
        assert_eq!(parse(&s), Some(st));
        // Только коллегам.
        let r = AutoReply { external: Text::default(), ..reply() };
        let s = script(&stored(r, None, None), &audience());
        assert!(s.contains("if address :domain :is \"from\" [\"corp.example\"] {\n    vacation :days 4"), "{s}");
        assert!(s.ends_with(";\n}\n"));
        assert_eq!(s.matches("vacation :days").count(), 1);
    }

    #[test]
    fn foreign_scripts_are_not_ours() {
        assert_eq!(parse("require \"vacation\";\nvacation \"x\";"), None);
        assert_eq!(parse(&format!("{HEADER}\nrequire [\"vacation\"];")), None);
        assert_eq!(parse(&format!("{HEADER}\n# settings: {{broken")), None);
    }

    /// «Вне офиса»: дни периода в поясе пользователя, конец в полночь не входит.
    #[test]
    fn out_of_office_covers_whole_days() {
        let tz = jiff::tz::TimeZone::get("Europe/Moscow").unwrap();
        // Ср 09:00 — пт 18:00 по Москве: ср, чт, пт.
        let e = out_of_office("Вне офиса", "2026-10-21T06:00:00Z", "2026-10-23T15:00:00Z", &tz, "u1", "cal").unwrap();
        assert_eq!((e["start"].as_str(), e["duration"].as_str()), (Some("2026-10-21T00:00:00"), Some("P3D")));
        assert_eq!((e["showWithoutTime"].as_bool(), e["freeBusyStatus"].as_str()), (Some(true), Some("busy")));
        assert_eq!(e["calendarIds"]["cal"], true);
        // «по 23.10» без времени — полночь 24-го: 21, 22, 23.
        let e = out_of_office("x", "2026-10-20T21:00:00Z", "2026-10-23T21:00:00Z", &tz, "u1", "cal").unwrap();
        assert_eq!(e["duration"].as_str(), Some("P3D"));
        assert!(out_of_office("x", "2026-10-23T21:00:00Z", "2026-10-20T21:00:00Z", &tz, "u1", "cal").is_none());
        assert!(out_of_office("x", "вчера", "2026-10-20T21:00:00Z", &tz, "u1", "cal").is_none());
    }
}
